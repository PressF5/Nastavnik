CREATE TABLE profile_matching_rule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_field_id  BIGINT NOT NULL UNIQUE,
    comparison_type   VARCHAR(40) NOT NULL,
    weight            NUMERIC(6, 2) NOT NULL DEFAULT 1.00,
    active            BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT        fk_profile_matching_rule_profile_field FOREIGN KEY (profile_field_id) REFERENCES profile_field (id),
    CONSTRAINT        chk_profile_matching_rule_weight CHECK (weight > 0 AND weight <= 100),
    CONSTRAINT        chk_profile_matching_rule_comparison_type
        CHECK (
            comparison_type IN (
                'EXACT_MATCH',
                'MULTISELECT_OVERLAP',
                'TEXT_WORD_OVERLAP',
                'NUMERIC_PROXIMITY',
                'BOOLEAN_MATCH'
            )
        )
);
