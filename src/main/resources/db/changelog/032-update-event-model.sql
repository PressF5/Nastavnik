-- Переводим даты в дату и время.
-- Для существующих записей начало будет установлено на 00:00,
-- окончание — на 23:59:59 последнего указанного дня.
ALTER TABLE event
    ADD COLUMN start_at TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN end_at TIMESTAMP WITHOUT TIME ZONE;

UPDATE event
SET start_at = start_date::TIMESTAMP,
    end_at = COALESCE(end_date, start_date)::TIMESTAMP
             + INTERVAL '23 hours 59 minutes 59 seconds';

ALTER TABLE event
    ALTER COLUMN start_at SET NOT NULL,
    ALTER COLUMN end_at SET NOT NULL;

ALTER TABLE event
    DROP CONSTRAINT chk_event_dates,
    DROP COLUMN start_date,
    DROP COLUMN end_date;

ALTER TABLE event
    ADD CONSTRAINT chk_event_dates
        CHECK (end_at > start_at);

-- Формат мероприятия.
ALTER TABLE event
    ADD COLUMN format VARCHAR(20);

UPDATE event
SET format = CASE
    WHEN location IS NULL THEN 'ONLINE'
    ELSE 'OFFLINE'
END;

ALTER TABLE event
    ALTER COLUMN format SET NOT NULL;

ALTER TABLE event
    ADD CONSTRAINT chk_event_format
        CHECK (format IN ('ONLINE', 'OFFLINE', 'HYBRID'));

-- Место обязательно для очных и гибридных мероприятий.
ALTER TABLE event
    ADD CONSTRAINT chk_event_location
        CHECK (
            (format = 'ONLINE' AND location IS NULL)
            OR
            (format IN ('OFFLINE', 'HYBRID') AND location IS NOT NULL)
        );

-- Снимок организатора на момент создания мероприятия.
ALTER TABLE event
    ADD COLUMN organizer_person_name VARCHAR(300),
    ADD COLUMN organizer_organization_name VARCHAR(500);

-- Старое поле организатора больше не используется.
ALTER TABLE event
    DROP COLUMN organizer;

-- Спикеры мероприятия.
CREATE TABLE event_speaker
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL,
    full_name   VARCHAR(300) NOT NULL,
    position    VARCHAR(300),
    sort_order  INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_event_speaker_event
        FOREIGN KEY (event_id) REFERENCES event (id) ON DELETE CASCADE
);

CREATE INDEX idx_event_speaker_event
    ON event_speaker (event_id);

-- Ссылки на материалы мероприятия.
CREATE TABLE event_material_link
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL,
    name        VARCHAR(200) NOT NULL,
    url         VARCHAR(1000) NOT NULL,
    sort_order  INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_event_material_event
        FOREIGN KEY (event_id) REFERENCES event (id) ON DELETE CASCADE
);

CREATE INDEX idx_event_material_event
    ON event_material_link (event_id);
