CREATE TABLE event
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    description TEXT,
    level       VARCHAR(20) NOT NULL,
    start_date  DATE NOT NULL,
    end_date    DATE,
    location    VARCHAR(300),
    organizer   VARCHAR(200),
    url         VARCHAR(1000),
    active      BOOLEAN NOT NULL DEFAULT TRUE,

    region_id   BIGINT NOT NULL,
    msu_id      BIGINT,
    created_by  BIGINT NOT NULL,

    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_event_region FOREIGN KEY (region_id) REFERENCES region (id),
    CONSTRAINT fk_event_msu FOREIGN KEY (msu_id) REFERENCES msu (id),
    CONSTRAINT fk_event_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT chk_event_level CHECK (level IN ('FEDERAL', 'REGIONAL', 'MUNICIPAL')),
    CONSTRAINT chk_event_msu_level
        CHECK (
            (level = 'MUNICIPAL' AND msu_id IS NOT NULL)
            OR
            (level IN ('FEDERAL', 'REGIONAL') AND msu_id IS NULL)
        ),
    CONSTRAINT chk_event_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX idx_event_region ON event (region_id);
CREATE INDEX idx_event_msu ON event (msu_id);
CREATE INDEX idx_event_level ON event (level);
CREATE INDEX idx_event_active ON event (active);